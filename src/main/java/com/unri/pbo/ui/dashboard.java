    private javax.swing.JPanel buatHalamanSementara(String judul) {
        javax.swing.JPanel p = new javax.swing.JPanel(new java.awt.BorderLayout());
        p.setBackground(new java.awt.Color(248, 245, 236));
        javax.swing.JLabel lbl = new javax.swing.JLabel(judul, javax.swing.SwingConstants.CENTER);
        lbl.setFont(new java.awt.Font("Yu Gothic UI Semibold", java.awt.Font.BOLD, 18));
        p.add(lbl, java.awt.BorderLayout.CENTER);
        return p;
    }

    private void gantiHalaman(String namaPage, javax.swing.JToggleButton tombolAktif) {
        java.awt.CardLayout cl = (java.awt.CardLayout) panelKonten.getLayout();
        cl.show(panelKonten, namaPage);

        javax.swing.JToggleButton[] semuaTombol = {
            btnProduk, btnKasir, btnPenjualan, btnPembelian, btnRestock, btnRiwayat
        };
        for (javax.swing.JToggleButton btn : semuaTombol) {
            if (btn == tombolAktif) {
                btn.setBackground(new java.awt.Color(240, 138, 36));
            } else {
                btn.setBackground(java.awt.Color.WHITE);
            }
        }
    }
  

